    private static var counter: UInt8 = 0

    public static func bytes(for r: ControllerReport) -> [UInt8] {
        var out = [UInt8](repeating: 0, count: size)
        out[0] = 0x01
        out[1] = GamepadReport.axisByte(r.leftX)
        out[2] = GamepadReport.axisByte(r.leftY, inverted: true)
        out[3] = GamepadReport.axisByte(r.rightX)
        out[4] = GamepadReport.axisByte(r.rightY, inverted: true)
        let b = r.buttons
        var b5 = GamepadReport.hat(for: b) & 0x0F
        if b.contains(.x) { b5 |= 1 << 4 }        // square
        if b.contains(.a) { b5 |= 1 << 5 }        // cross
        if b.contains(.b) { b5 |= 1 << 6 }        // circle
        if b.contains(.y) { b5 |= 1 << 7 }        // triangle
        out[5] = b5
        var b6: UInt8 = 0
        if b.contains(.leftShoulder) { b6 |= 1 << 0 }
        if b.contains(.rightShoulder) { b6 |= 1 << 1 }
        if r.leftTrigger > 0 { b6 |= 1 << 2 }
        if r.rightTrigger > 0 { b6 |= 1 << 3 }
        if b.contains(.options) { b6 |= 1 << 4 }  // share
        if b.contains(.menu) { b6 |= 1 << 5 }     // options
        if b.contains(.leftThumbstick) { b6 |= 1 << 6 }
        if b.contains(.rightThumbstick) { b6 |= 1 << 7 }
        out[6] = b6
        counter &+= 1
        out[7] = (b.contains(.home) ? 1 : 0) | (counter << 2)
        out[8] = r.leftTrigger
        out[9] = r.rightTrigger
        out[12] = 0xFF                              // battery: full, plugged in
        out[30] = 0x1B                              // battery status: full, cable
        out[33] = 0x00                              // no touches
        out[35] = 0x80                              // touch 1 inactive
        out[39] = 0x80                              // touch 2 inactive
        return out
    }

    /// Benign answers for the reports the driver reads on attach:
    /// calibration with zero bias and full-scale ranges, a fixed MAC address,
    /// and a firmware block.
    public static func featureReport(id: UInt8) -> [UInt8]? {
        switch id {
        case 0x02:
            var r = [UInt8](repeating: 0, count: 37)
            r[0] = 0x02
            func put(_ v: Int16, at i: Int) { r[i] = UInt8(truncatingIfNeeded: v); r[i + 1] = UInt8(truncatingIfNeeded: v >> 8) }
            // gyro bias pitch/yaw/roll = 0 at 1..6
            put(8192, at: 7); put(-8192, at: 9)      // pitch plus/minus
            put(8192, at: 11); put(-8192, at: 13)    // yaw
            put(8192, at: 15); put(-8192, at: 17)    // roll
            put(540, at: 19); put(540, at: 21)       // gyro speed plus/minus
            put(8192, at: 23); put(-8192, at: 25)    // acc x
            put(8192, at: 27); put(-8192, at: 29)    // acc y
            put(8192, at: 31); put(-8192, at: 33)    // acc z
            return r
        case 0x81:
            return [0x81, 0x1E, 0xBE, 0xA0, 0x00, 0x00, 0x01]
        case 0x12:
            return [0x12, 0x1E, 0xBE, 0xA0, 0x00, 0x00, 0x01, 0x08, 0x25, 0x00, 0x1E, 0x00, 0x1E, 0x00, 0x1E, 0x00]
        case 0xA3:
            return [0xA3] + [UInt8](repeating: 0, count: 48)
        default:
            return nil
        }
    }
}

/// Xbox Wireless Controller (Model 1708, firmware 5) Bluetooth reports.
public enum XboxOneReport {
    /// Input report 1, 17 bytes including the id:
    /// ```
    /// [0]      0x01
    /// [1-4]    left stick X, Y: UInt16 little-endian, 0-65535, centre 32768, Y down is positive
    /// [5-8]    right stick Z, Rz
    /// [9-10]   brake (left trigger) 0-1023, [11-12] accelerator (right trigger) 0-1023
    /// [13]     hat: 1-8 clockwise from up, 0 = released
    /// [14-15]  buttons 1-15, then bit 15 = View (AC Back)
    /// [16]     bit 0 = Share (Record), rest zero
    /// ```
    /// Report 2 carries the Xbox button as Consumer AC Home.
    public static let size = 17

    public static let descriptor: [UInt8] = [
        0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x85, 0x01,
        0x09, 0x01, 0xA1, 0x00, 0x09, 0x30, 0x09, 0x31, 0x15, 0x00, 0x27, 0xFF, 0xFF, 0x00, 0x00,
        0x95, 0x02, 0x75, 0x10, 0x81, 0x02, 0xC0,
        0x09, 0x01, 0xA1, 0x00, 0x09, 0x32, 0x09, 0x35, 0x15, 0x00, 0x27, 0xFF, 0xFF, 0x00, 0x00,
        0x95, 0x02, 0x75, 0x10, 0x81, 0x02, 0xC0,
        0x05, 0x02, 0x09, 0xC5, 0x15, 0x00, 0x26, 0xFF, 0x03, 0x95, 0x01, 0x75, 0x0A, 0x81, 0x02,
        0x15, 0x00, 0x25, 0x00, 0x75, 0x06, 0x95, 0x01, 0x81, 0x03,
        0x05, 0x02, 0x09, 0xC4, 0x15, 0x00, 0x26, 0xFF, 0x03, 0x95, 0x01, 0x75, 0x0A, 0x81, 0x02,
        0x15, 0x00, 0x25, 0x00, 0x75, 0x06, 0x95, 0x01, 0x81, 0x03,
        0x05, 0x01, 0x09, 0x39, 0x15, 0x01, 0x25, 0x08, 0x35, 0x00, 0x46, 0x3B, 0x01, 0x66, 0x14, 0x00,
        0x75, 0x04, 0x95, 0x01, 0x81, 0x42,
        0x75, 0x04, 0x95, 0x01, 0x15, 0x00, 0x25, 0x00, 0x35, 0x00, 0x45, 0x00, 0x65, 0x00, 0x81, 0x03,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x0F, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x0F, 0x81, 0x02,
        0x05, 0x0C, 0x0A, 0x24, 0x02, 0x15, 0x00, 0x25, 0x01, 0x95, 0x01, 0x75, 0x01, 0x81, 0x02,
        0x05, 0x0C, 0x0A, 0xB2, 0x00, 0x15, 0x00, 0x25, 0x01, 0x95, 0x01, 0x75, 0x01, 0x81, 0x02,
        0x15, 0x00, 0x25, 0x00, 0x75, 0x07, 0x95, 0x01, 0x81, 0x03,
        0xC0,
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x02,
        0x0A, 0x23, 0x02, 0x15, 0x00, 0x25, 0x01, 0x95, 0x01, 0x75, 0x01, 0x81, 0x02,
        0x15, 0x00, 0x25, 0x00, 0x75, 0x07, 0x95, 0x01, 0x81, 0x03,
        0xC0,
    ]

    public static func bytes(for r: ControllerReport) -> [UInt8] {
        var out = [UInt8](repeating: 0, count: size)
        out[0] = 0x01
        func put16(_ v: UInt16, at i: Int) { out[i] = UInt8(v & 0xFF); out[i + 1] = UInt8(v >> 8) }
        put16(axis16(r.leftX), at: 1)
        put16(axis16(r.leftY, inverted: true), at: 3)
        put16(axis16(r.rightX), at: 5)
        put16(axis16(r.rightY, inverted: true), at: 7)
        put16(UInt16(r.leftTrigger) * 1023 / 255, at: 9)
        put16(UInt16(r.rightTrigger) * 1023 / 255, at: 11)
        let hat = GamepadReport.hat(for: r.buttons)
        out[13] = hat == 8 ? 0 : hat + 1
        var bits: UInt16 = 0
        let b = r.buttons
        if b.contains(.a) { bits |= 1 << 0 }
        if b.contains(.b) { bits |= 1 << 1 }
        if b.contains(.x) { bits |= 1 << 3 }
        if b.contains(.y) { bits |= 1 << 4 }
        if b.contains(.leftShoulder) { bits |= 1 << 6 }
        if b.contains(.rightShoulder) { bits |= 1 << 7 }
        if b.contains(.menu) { bits |= 1 << 11 }
        if b.contains(.leftThumbstick) { bits |= 1 << 13 }
        if b.contains(.rightThumbstick) { bits |= 1 << 14 }
        if b.contains(.options) { bits |= 1 << 15 }   // View, Consumer AC Back
        out[14] = UInt8(bits & 0xFF)
        out[15] = UInt8(bits >> 8)
        return out
    }

    /// Report 2: the Xbox button.
    public static func homeReport(pressed: Bool) -> [UInt8] {
        [0x02, pressed ? 0x01 : 0x00]
    }

    static func axis16(_ value: Int16, inverted: Bool = false) -> UInt16 {
        let v = inverted ? -Int(value) : Int(value)
        return UInt16(clamping: (v + 32767) * 65535 / 65534)
    }
}
