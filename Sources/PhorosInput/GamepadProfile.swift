/// The identity a `VirtualGamepad` presents to the host operating system.
///
/// macOS's GameController framework only adopts controllers it has a
/// profile for. A generic HID gamepad is visible to raw-HID code paths, but
/// `GCController` never lists it and each game guesses its own layout. The
/// two console profiles reuse the identity, report descriptor and report
/// layout of a real controller, so the system applies its built-in mapping
/// and every game sees the same buttons.
public enum GamepadProfile: String, CaseIterable, Codable, Sendable {
    /// Generic desktop gamepad, our own vendor and product id. Works with raw
    /// HID readers only.
    case generic
    /// Sony DualShock 4 (second revision) over USB.
    case dualShock4
    /// Microsoft Xbox Wireless Controller (Model 1708, firmware 5) over Bluetooth.
    case xboxOne

    public var vendorID: Int {
        switch self {
        case .generic: return GamepadReport.vendorID
        case .dualShock4: return 0x054C
        case .xboxOne: return 0x045E
        }
    }

    public var productID: Int {
        switch self {
        case .generic: return GamepadReport.productID
        case .dualShock4: return 0x09CC
        case .xboxOne: return 0x02FD
        }
    }

    public var versionNumber: Int {
        switch self {
        case .generic: return 1
        case .dualShock4: return 0x0100
        case .xboxOne: return 0x0903
        }
    }

    /// The name the system shows. Real controllers use these exact strings
    /// and some matching keys on them.
    public var productName: String {
        switch self {
        case .generic: return "Phoros Controller"
        case .dualShock4: return "Wireless Controller"
        case .xboxOne: return "Xbox Wireless Controller"
        }
    }

    public var manufacturer: String {
        switch self {
        case .generic: return "Phoros"
        case .dualShock4: return "Sony Interactive Entertainment"
        case .xboxOne: return "Microsoft"
        }
    }

    public var transport: String {
        switch self {
        case .generic: return "Virtual"
        case .dualShock4: return "USB"
        case .xboxOne: return "Bluetooth"
        }
    }

    public var descriptor: [UInt8] {
        switch self {
        case .generic: return GamepadReport.descriptor
        case .dualShock4: return DualShock4Report.descriptor
        case .xboxOne: return XboxOneReport.descriptor
        }
    }

    /// One input report for `report`, including the report id where the
    /// profile uses one.
    public func inputReport(for report: ControllerReport) -> [UInt8] {
        switch self {
        case .generic: return GamepadReport.bytes(for: report)
        case .dualShock4: return DualShock4Report.bytes(for: report)
        case .xboxOne: return XboxOneReport.bytes(for: report)
        }
    }

    /// The answer to a feature-report read, or `nil` for reports the profile
    /// does not answer. Some system drivers read calibration or identity
    /// reports before they trust a device.
    public func featureReport(id: UInt8) -> [UInt8]? {
        switch self {
        case .generic, .xboxOne: return nil
        case .dualShock4: return DualShock4Report.featureReport(id: id)
        }
    }
}

